CREATE TABLE assessment_sheet_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id BIGINT NOT NULL,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(50) NOT NULL,
    max_score DECIMAL(5, 2) NOT NULL DEFAULT 100,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_assessment_sheet_type UNIQUE (sheet_id, code),
    CONSTRAINT fk_ast_sheet FOREIGN KEY (sheet_id) REFERENCES assessment_sheets (id) ON DELETE CASCADE
);

CREATE INDEX idx_ast_sheet ON assessment_sheet_types (sheet_id, sort_order);

ALTER TABLE assessment_sheet_cells
    ADD COLUMN type_code VARCHAR(30) NOT NULL DEFAULT 'SCORE';

ALTER TABLE assessment_sheet_cells
    DROP CONSTRAINT uk_assessment_cell;

ALTER TABLE assessment_sheet_cells
    ADD CONSTRAINT uk_assessment_cell UNIQUE (column_id, student_id, type_code);
